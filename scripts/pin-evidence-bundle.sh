#!/bin/sh
# pin-evidence-bundle.sh — pin the canonical Gauntlet evidence bundle.
#
# Writes .agents/reports/evidence-bundle.sha256 in `sha256sum -c`
# compatible form, with every path relative to the repository root, so
# the bundle verifies from the repo root with:
#
#     sha256sum -c .agents/reports/evidence-bundle.sha256
#
# Pinned inputs (charter task27 decision 10 — the pinned bundle IS the
# canonical export of this build):
#   - .agents/reports/conformance.json
#   - every file under the CURRENT sweep's conformance-evidence dir
#     (the <UTC-stamp> subdir; given as the optional argument, else the
#     newest stamp under .agents/reports/conformance-evidence/)
#   - .agents/reports/handoff.md
#   - .agents/reports/baselines.json
#   - .agents/reports/mutation.json
#
# Usage:
#   scripts/pin-evidence-bundle.sh [evidence-dir]   # write the pin
#   scripts/pin-evidence-bundle.sh --check          # verify the pin
#
# Refuses with a clear message and a non-zero exit if ANY input is
# missing. POSIX sh; no dependencies beyond sha256sum(1), find(1),
# sort(1).

set -eu

ROOT=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
REPORTS_DIR="$ROOT/.agents/reports"
EVIDENCE_ROOT="$REPORTS_DIR/conformance-evidence"
BUNDLE="$REPORTS_DIR/evidence-bundle.sha256"

die() {
    echo "pin-evidence-bundle: $2" >&2
    exit "$1"
}

# Resolve the sweep evidence dir: the argument (relative to the repo
# root or absolute), else the newest UTC-stamp subdir. Stamp names are
# generated by the sweep (digits + 'Z'), so lexical sort is date sort.
MODE=pin
EVIDENCE_ARG=
for arg in "$@"; do
    case "$arg" in
        --check) MODE=check ;;
        -h|--help)
            sed -n '2,30p' "$0" | sed 's/^# \{0,1\}//'
            exit 0
            ;;
        -*) die 2 "unknown option: $arg (usage: $0 [--check] [evidence-dir])" ;;
        *)
            [ -z "$EVIDENCE_ARG" ] || die 2 "one evidence-dir at most"
            EVIDENCE_ARG=$arg
            ;;
    esac
done

# --- check mode: verify the committed bundle -------------------------------
if [ "$MODE" = check ]; then
    [ -z "$EVIDENCE_ARG" ] || die 2 "--check takes no evidence-dir (the bundle names its own paths)"
    [ -f "$BUNDLE" ] || die 1 "missing bundle: $BUNDLE"
    # sha256sum -c resolves the bundle's repo-relative paths; run from
    # the root so they resolve exactly as pinned.
    if (cd "$ROOT" && sha256sum -c "$BUNDLE"); then
        echo "pin-evidence-bundle: bundle verified: $BUNDLE"
        exit 0
    fi
    die 1 "bundle verification FAILED: $BUNDLE"
fi

# --- pin mode: collect inputs ----------------------------------------------
EVIDENCE_DIR=
if [ -n "$EVIDENCE_ARG" ]; then
    case "$EVIDENCE_ARG" in
        /*) EVIDENCE_DIR=$EVIDENCE_ARG ;;
        *)  EVIDENCE_DIR="$ROOT/$EVIDENCE_ARG" ;;
    esac
else
    [ -d "$EVIDENCE_ROOT" ] || die 1 "missing evidence root: $EVIDENCE_ROOT"
    # shellcheck disable=SC2012  # names are sweep-generated UTC stamps ([0-9T Z])
    EVIDENCE_DIR=$(ls -1 "$EVIDENCE_ROOT" | sort | tail -n 1)
    [ -n "$EVIDENCE_DIR" ] || die 1 "no sweep dir under: $EVIDENCE_ROOT"
    EVIDENCE_DIR="$EVIDENCE_ROOT/$EVIDENCE_DIR"
fi
[ -d "$EVIDENCE_DIR" ] || die 1 "missing evidence dir: $EVIDENCE_DIR"

# The evidence dir must live under the repo root: every pinned path is
# repo-relative so `sha256sum -c` works from the root verbatim.
case "$EVIDENCE_DIR" in
    "$ROOT"/*) REL_EVIDENCE=${EVIDENCE_DIR#"$ROOT"/} ;;
    *) die 1 "evidence dir is outside the repo root: $EVIDENCE_DIR" ;;
esac

SINGLETS="
.agents/reports/conformance.json
.agents/reports/handoff.md
.agents/reports/baselines.json
.agents/reports/mutation.json
"

for f in $SINGLETS; do
    [ -f "$ROOT/$f" ] || die 1 "missing bundle input: $f"
done

EVIDENCE_FILES=$(cd "$ROOT" && find "$REL_EVIDENCE" -type f | sort)
[ -n "$EVIDENCE_FILES" ] || die 1 "no files under evidence dir: $EVIDENCE_DIR"

# --- write the bundle --------------------------------------------------------
TMP="$BUNDLE.tmp"
{
    echo "# gauntlet evidence bundle (generated $(date -u +%Y-%m-%dT%H:%M:%SZ))"
    echo "# verify from the repo root: sha256sum -c $BUNDLE"
    echo "# evidence dir: $REL_EVIDENCE"
    for f in $SINGLETS; do
        (cd "$ROOT" && sha256sum "$f")
    done
    for f in $EVIDENCE_FILES; do
        (cd "$ROOT" && sha256sum "$f")
    done
} > "$TMP"
mv "$TMP" "$BUNDLE"

echo "pin-evidence-bundle: pinned $(grep -c -v '^#' "$BUNDLE") files -> $BUNDLE"
