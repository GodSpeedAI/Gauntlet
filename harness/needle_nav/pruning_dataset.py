def compute_dataset_sha256() -> str:
    """Computes a deterministic digest of the 16 pruning horizons."""
    horizons = make_pruning_horizons()
    records = []
    for h in horizons:
        records.append({
            "horizon_id": h.horizon_id,
            "family": h.family,
            "state_summary": h.state_summary,
            "candidates": [
                {
                    "affordance_id": c.affordance_id,
                    "description": c.description,
                    "consequence": c.consequence.value,
                    "probe_wall_clock_ms": c.probe_wall_clock_ms,
                }
                for c in h.candidates
            ],
            "probe_budget_k": h.probe_budget_k,
            "state_hash": h.state_hash,
        })
    canonical_bytes = json.dumps(records, sort_keys=True, indent=2).encode("utf-8")
    return hashlib.sha256(canonical_bytes).hexdigest()
